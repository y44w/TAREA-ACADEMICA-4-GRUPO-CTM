// Activar modo nocturno por defecto en la versión modificada
function setDefaultDarkMode() {
  darkModeSwitch.checked = true;
  root.setAttribute("data-theme", "dark");
  bgColorPicker.value = "#0b1120";
  textColorPicker.value = "#f3f4f6";
}
setDefaultDarkMode();

customizerToggle.addEventListener("click", () => {
  customizerDrawer.classList.toggle("open");
});

openCustomizeNavBtn.addEventListener("click", () => {
  customizerDrawer.classList.add("open");
});

function applyLanguage(lang) {
  const dict = translations[lang] || translations.es;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  root.setAttribute("lang", lang);
  langSelect.value = lang;
  if (lang === "ja") {
    root.style.setProperty("--font-family", "'Noto Sans JP', 'Montserrat', sans-serif");
    fontFamilySelect.value = "'Noto Sans JP', sans-serif";
  }
  updateVersionButtonLabel();
}

darkModeSwitch.addEventListener("change", (e) => {
  const isDark = e.target.checked;
  root.setAttribute("data-theme", isDark ? "dark" : "light");
  root.style.removeProperty("--bg-color");
  root.style.removeProperty("--text-color");
});

langSelect.addEventListener("change", (e) => applyLanguage(e.target.value));
jpLangBtn.addEventListener("click", () => applyLanguage("ja"));

primaryColorPicker.addEventListener("input", (e) => root.style.setProperty("--primary-color", e.target.value));
bgColorPicker.addEventListener("input", (e) => root.style.setProperty("--bg-color", e.target.value));
textColorPicker.addEventListener("input", (e) => root.style.setProperty("--text-color", e.target.value));
fontFamilySelect.addEventListener("change", (e) => root.style.setProperty("--font-family", e.target.value));
fontSizeRange.addEventListener("input", (e) => {
  const size = `${e.target.value}px`;
  fontSizeValue.textContent = size;
  root.style.setProperty("--base-font-size", size);
});

resetSettings.addEventListener("click", () => {
  root.style.removeProperty("--primary-color");
  root.style.removeProperty("--bg-color");
  root.style.removeProperty("--text-color");
  root.style.removeProperty("--font-family");
  root.style.removeProperty("--base-font-size");

  setDefaultDarkMode();
  primaryColorPicker.value = "#004B93";
  fontFamilySelect.value = "'Montserrat', sans-serif";
  fontSizeRange.value = 17;
  fontSizeValue.textContent = "17px";
  applyLanguage("es");
});

// Animación de copos de nieve al pulsar el botón
const snowContainer = document.getElementById("snow-container");
let snowActive = false;

function toggleSnowflakes() {
  snowActive = !snowActive;
  snowToggleBtn.classList.toggle("active", snowActive);
  snowContainer.innerHTML = "";
  if (!snowActive) return;

  const flakeChars = ["❄", "❅", "✼"];
  for (let i = 0; i < 42; i++) {
    const flake = document.createElement("span");
    flake.classList.add("snowflake");
    flake.textContent = flakeChars[i % flakeChars.length];
    const size = Math.random() * 14 + 12;
    flake.style.fontSize = `${size}px`;
    flake.style.left = `${Math.random() * 100}%`;
    flake.style.animationDuration = `${Math.random() * 7 + 6}s`;
    flake.style.animationDelay = `${Math.random() * 5}s`;
    snowContainer.appendChild(flake);
  }
}

snowToggleBtn.addEventListener("click", toggleSnowflakes);

// Alternar entre página ANTES y DESPUÉS de las modificaciones
const toggleVersionBtn = document.getElementById("toggleVersionBtn");
const versionLabel = document.getElementById("versionLabel");
let isAfterVersion = true;

function updateVersionButtonLabel() {
  const lang = root.getAttribute("lang") || "es";
  if (lang === "ja") {
    versionLabel.textContent = isAfterVersion ? "表示: 変更後 (修正版)" : "表示: 変更前 (元データ)";
  } else if (lang === "en") {
    versionLabel.textContent = isAfterVersion ? "View: After (Modified)" : "View: Before (Original)";
  } else {
    versionLabel.textContent = isAfterVersion ? "Ver: Después (Modificada)" : "Ver: Antes (Original)";
  }
}

toggleVersionBtn.addEventListener("click", () => {
  isAfterVersion = !isAfterVersion;
  document.body.classList.toggle("modified-mode", isAfterVersion);
  document.body.classList.toggle("before-mode", !isAfterVersion);
  if (isAfterVersion) {
    setDefaultDarkMode();
  }
  updateVersionButtonLabel();
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("active");
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll(".reveal").forEach((sec) => revealObserver.observe(sec));

function createBubbles() {
  const container = document.getElementById("bubbles-container");
  for (let i = 0; i < 22; i++) {
    const bubble = document.createElement("span");
    bubble.classList.add("bubble");
    const size = Math.random() * 24 + 8;
    bubble.style.width = `${size}px`;
    bubble.style.height = `${size}px`;
    bubble.style.left = `${Math.random() * 100}%`;
    bubble.style.animationDuration = `${Math.random() * 10 + 7}s`;
    bubble.style.animationDelay = `${Math.random() * 5}s`;
    container.appendChild(bubble);
  }
}
createBubbles();

