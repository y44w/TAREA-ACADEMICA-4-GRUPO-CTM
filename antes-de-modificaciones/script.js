const root = document.documentElement;
const customizerDrawer = document.getElementById("customizerDrawer");
const customizerToggle = document.getElementById("customizerToggle");

const darkModeSwitch = document.getElementById("darkModeSwitch");
const langSelect = document.getElementById("langSelect");
const primaryColorPicker = document.getElementById("primaryColorPicker");
const bgColorPicker = document.getElementById("bgColorPicker");
const textColorPicker = document.getElementById("textColorPicker");
const fontFamilySelect = document.getElementById("fontFamilySelect");
const fontSizeRange = document.getElementById("fontSizeRange");
const fontSizeValue = document.getElementById("fontSizeValue");
const resetSettings = document.getElementById("resetSettings");

customizerToggle.addEventListener("click", () => {
  customizerDrawer.classList.toggle("open");
});

function applyLanguage(lang) {
  const dict = translations[lang] || translations.es;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  root.setAttribute("lang", lang);
}

darkModeSwitch.addEventListener("change", (e) => {
  const isDark = e.target.checked;
  root.setAttribute("data-theme", isDark ? "dark" : "light");
  root.style.removeProperty("--bg-color");
  root.style.removeProperty("--text-color");
});

langSelect.addEventListener("change", (e) => applyLanguage(e.target.value));
primaryColorPicker.addEventListener("input", (e) => root.style.setProperty("--primary-color", e.target.value));
bgColorPicker.addEventListener("input", (e) => root.style.setProperty("--bg-color", e.target.value));
textColorPicker.addEventListener("input", (e) => root.style.setProperty("--text-color", e.target.value));
fontFamilySelect.addEventListener("change", (e) => root.style.setProperty("--font-family", e.target.value));
fontSizeRange.addEventListener("input", (e) => {
  const size = `${e.target.value}px`;
  fontSizeValue.textContent = size;
  root.style.setProperty("--base-font-size", size);
});

resetSettings.addEventListener("click", () => {
  darkModeSwitch.checked = false;
  root.setAttribute("data-theme", "light");
  root.style.removeProperty("--primary-color");
  root.style.removeProperty("--bg-color");
  root.style.removeProperty("--text-color");
  root.style.removeProperty("--font-family");
  root.style.removeProperty("--base-font-size");

  primaryColorPicker.value = "#004B93";
  bgColorPicker.value = "#f4f7fb";
  textColorPicker.value = "#111827";
  fontFamilySelect.value = "'Montserrat', sans-serif";
  fontSizeRange.value = 16;
  fontSizeValue.textContent = "16px";
  langSelect.value = "es";
  applyLanguage("es");
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("active");
    });
  },
  { threshold: 0.15 }
);

document.querySelectorAll(".reveal").forEach((sec) => revealObserver.observe(sec));

function createBubbles() {
  const container = document.getElementById("bubbles-container");
  for (let i = 0; i < 22; i++) {
    const bubble = document.createElement("span");
    bubble.classList.add("bubble");
    const size = Math.random() * 24 + 8;
    bubble.style.width = `${size}px`;
    bubble.style.height = `${size}px`;
    bubble.style.left = `${Math.random() * 100}%`;
    bubble.style.animationDuration = `${Math.random() * 10 + 7}s`;
    bubble.style.animationDelay = `${Math.random() * 5}s`;
    container.appendChild(bubble);
  }
}
createBubbles();

document.querySelectorAll(".tilt-card").forEach((card) => {
  card.addEventListener("mousemove", (e) => {
    const rect = card.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    const rotateX = ((y - rect.height / 2) / rect.height) * -5;
    const rotateY = ((x - rect.width / 2) / rect.width) * 5;
    card.style.transform = `perspective(900px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale(1.01)`;
  });
  card.addEventListener("mouseleave", () => {
    card.style.transform = "perspective(900px) rotateX(0) rotateY(0) scale(1)";
  });
});

